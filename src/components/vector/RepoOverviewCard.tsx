import { useState } from "react";
import {
  BookOpen,
  Check,
  ChevronDown,
  ChevronRight,
  Copy,
  Download,
  FileCode,
  FolderGit2,
  Shield,
} from "lucide-react";
import { toast } from "sonner";
import type { RepoOverviewData } from "@/lib/api";
import { SummaryCard } from "./SummaryCard";

export function RepoOverviewCard({
  data,
  model,
  provider,
}: {
  data: RepoOverviewData;
  model?: string | undefined;
  provider?: string | undefined;
}) {
  const [copied, setCopied] = useState(false);
  const [expandedFile, setExpandedFile] = useState<string | null>(null);

  const handleCopy = () => {
    const lines = [
      `# Repository: ${data.repo_name}`,
      `URL: ${data.url}`,
      "",
      "## Overview",
      data.overview,
      "",
      "## Start Reading Here",
      ...data.start_here.map((s, idx) => `${idx + 1}. **\`${s.path}\`**: ${s.reason}`),
      "",
      `## Files Analysed (${data.files.length})`,
      ...data.files.map((f) => `- \`${f.path}\`: ${f.summary.tldr}`),
    ];
    navigator.clipboard.writeText(lines.join("\n"));
    setCopied(true);
    toast.success("Repository summary copied");
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const lines = [
      `# Repository Overview: ${data.repo_name}`,
      `*Generated by Vector · Model: ${model || "local"} (${provider || "ollama"})*`,
      "",
      "## Architecture Overview",
      data.overview,
      "",
      "## Start Reading Here",
      ...data.start_here.map((s, idx) => `${idx + 1}. **\`${s.path}\`**: ${s.reason}`),
      "",
      `## Per-File Summaries (${data.files.length} files)`,
      "",
      ...data.files.flatMap((f) => [
        `### \`${f.path}\``,
        `**TL;DR:** ${f.summary.tldr}`,
        "",
        `**Purpose:** ${f.summary.purpose}`,
        "",
        f.summary.key_functions.length > 0 ? "**Key Functions:**" : "",
        ...f.summary.key_functions.map((fn) => `- \`${fn.name}\`: ${fn.summary}`),
        "",
      ]),
    ];
    const blob = new Blob([lines.join("\n")], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${data.repo_name.replace(/[/\\?%*:|"<>]/g, "_")}_overview.md`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success("Downloaded repository summary (.md)");
  };

  return (
    <div className="w-full rounded-2xl border bg-card p-5 shadow-sm transition-all">
      {/* Header */}
      <div className="flex flex-wrap items-center justify-between gap-3 border-b pb-4">
        <div className="flex items-center gap-2.5">
          <div className="flex h-9 w-9 items-center justify-center rounded-xl bg-primary/10 text-primary">
            <FolderGit2 className="h-5 w-5" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h3 className="font-semibold text-base">{data.repo_name}</h3>
              {provider === "hosted" ? (
                <span className="rounded-full bg-amber-500/15 px-2 py-0.5 text-[10px] font-semibold text-amber-600 dark:text-amber-400">
                  Hosted
                </span>
              ) : (
                <span className="flex items-center gap-1 rounded-full bg-chart-2/15 px-2 py-0.5 text-[10px] font-medium text-chart-2">
                  <Shield className="h-2.5 w-2.5" />
                  Local
                </span>
              )}
            </div>
            <p className="text-xs text-muted-foreground">
              {data.file_count} files analysed · {model || "default"}
            </p>
          </div>
        </div>

        {/* Actions */}
        <div className="flex items-center gap-1.5">
          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 rounded-lg border px-2.5 py-1.5 text-xs font-medium hover:bg-accent transition-colors"
          >
            {copied ? (
              <Check className="h-3.5 w-3.5 text-chart-2" />
            ) : (
              <Copy className="h-3.5 w-3.5" />
            )}
            {copied ? "Copied" : "Copy"}
          </button>
          <button
            onClick={handleDownload}
            className="flex items-center gap-1.5 rounded-lg border px-2.5 py-1.5 text-xs font-medium hover:bg-accent transition-colors"
          >
            <Download className="h-3.5 w-3.5" />
            Download .md
          </button>
        </div>
      </div>

      {/* Architectural Overview */}
      <div className="mt-4 space-y-2">
        <h4 className="text-xs font-semibold uppercase tracking-wider text-muted-foreground flex items-center gap-1.5">
          <BookOpen className="h-3.5 w-3.5 text-primary" />
          Repository Overview
        </h4>
        <div className="rounded-xl bg-muted/40 p-3.5 text-sm leading-relaxed whitespace-pre-line text-foreground/90">
          {data.overview}
        </div>
      </div>

      {/* Start Reading Here */}
      {data.start_here.length > 0 && (
        <div className="mt-5 space-y-2.5">
          <h4 className="text-xs font-semibold uppercase tracking-wider text-primary">
            Start Reading Here
          </h4>
          <div className="space-y-1.5">
            {data.start_here.map((item, idx) => (
              <div
                key={item.path}
                className="flex items-start gap-3 rounded-xl border bg-background/60 p-3 text-xs transition-colors hover:bg-accent/40"
              >
                <span className="flex h-5 w-5 shrink-0 items-center justify-center rounded-full bg-primary/10 font-mono text-[11px] font-semibold text-primary">
                  {idx + 1}
                </span>
                <div className="min-w-0 flex-1">
                  <p className="font-mono font-medium text-foreground">{item.path}</p>
                  <p className="mt-0.5 text-muted-foreground">{item.reason}</p>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Per-file Summaries */}
      {data.files.length > 0 && (
        <div className="mt-5 space-y-2">
          <h4 className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">
            Per-File Summaries ({data.files.length})
          </h4>
          <div className="divide-y rounded-xl border bg-background/40">
            {data.files.map((f) => {
              const isExpanded = expandedFile === f.path;
              return (
                <div key={f.path} className="p-2.5">
                  <button
                    onClick={() => setExpandedFile(isExpanded ? null : f.path)}
                    className="flex w-full items-center justify-between text-left hover:text-primary transition-colors"
                  >
                    <div className="flex items-center gap-2 min-w-0 pr-2">
                      <FileCode className="h-4 w-4 shrink-0 text-muted-foreground" />
                      <span className="font-mono text-xs font-medium truncate">{f.path}</span>
                    </div>
                    <div className="flex items-center gap-2 shrink-0">
                      {f.cached && (
                        <span className="rounded bg-chart-2/10 px-1.5 py-0.5 text-[10px] text-chart-2">
                          cached
                        </span>
                      )}
                      {isExpanded ? (
                        <ChevronDown className="h-4 w-4 text-muted-foreground" />
                      ) : (
                        <ChevronRight className="h-4 w-4 text-muted-foreground" />
                      )}
                    </div>
                  </button>
                  <p className="mt-1 pl-6 text-xs text-muted-foreground line-clamp-1">
                    {f.summary.tldr}
                  </p>

                  {isExpanded && (
                    <div className="mt-3 pl-6 pr-2 pb-2">
                      <SummaryCard
                        result={{
                          id: 0,
                          summary: f.summary,
                          cached: f.cached,
                          model: model || "local",
                          provider: provider || "ollama",
                        }}
                      />
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        </div>
      )}
    </div>
  );
}
