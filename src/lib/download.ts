import { getState, setState, uid, type Chat } from "./store";

export function renderChat(chat: Chat, format: "md" | "txt" | "json") {
  if (format === "json") return JSON.stringify(chat, null, 2);
  const lines = [
    `# ${chat.title}`,
    `Generated by Vector · ${new Date(chat.updatedAt).toLocaleString()}`,
    "",
  ];
  if (chat.sources.length) {
    lines.push(
      "## Inputs",
      ...chat.sources.map((s) => `- ${s.name}${s.url ? ` — ${s.url}` : ""}`),
      "",
    );
  }
  for (const m of chat.messages) {
    lines.push(
      m.role === "user" ? `## Request` : `## Summary${m.model ? ` (${m.model})` : ""}`,
      m.content || "_(no text)_",
      "",
    );
  }
  return lines.join("\n");
}

export function downloadChat(chatId: string, format: "md" | "txt" | "json", record = true) {
  const chat = getState().chats.find((c) => c.id === chatId);
  if (!chat) return;
  const body = renderChat(chat, format);
  const filename = `${chat.title.replace(/[^\w-]+/g, "_").slice(0, 50) || "summary"}.${format}`;
  const url = URL.createObjectURL(
    new Blob([body], { type: format === "json" ? "application/json" : "text/plain" }),
  );
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
  if (record)
    setState((s) => ({
      ...s,
      downloads: [{ id: uid(), chatId, filename, format, at: Date.now() }, ...s.downloads],
    }));
}
